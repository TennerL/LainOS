BITS 64
DEFAULT REL

GLOBAL console_init
GLOBAL console_clear
GLOBAL console_puts
GLOBAL console_newline
GLOBAL console_put_hex64
GLOBAL console_put_hex32
GLOBAL console_put_dec64
GLOBAL console_kprintf1
GLOBAL console_kprintf2
GLOBAL console_panic
GLOBAL console_read_line

FONT_W equ 8
FONT_H equ 8
FG_COLOR equ 0x00F725FC
BG_COLOR equ 0x0035063E
PANIC_BG_COLOR equ 0x00000080

SECTION .bss
cursor_x        resd 1
cursor_y        resd 1
cursor_visible  resb 1
cursor_ticks    resd 1
fb_base         resq 1
fb_width        resd 1
fb_height       resd 1
fb_pitch        resd 1
dec_buffer      resb 32
dec_buffer_end:

SECTION .text
console_init:
    mov [fb_base], rdi
    mov [fb_width], esi
    mov [fb_height], edx
    mov [fb_pitch], ecx
    ret

console_clear:
    push rax
    mov eax, BG_COLOR
    call fill_screen_color
    mov dword [cursor_x], 16
    mov dword [cursor_y], 16
    pop rax
    ret

console_newline:
    mov dword [cursor_x], 16
    add dword [cursor_y], FONT_H + 2

    mov eax, [cursor_y]
    add eax, FONT_H
    cmp eax, [fb_height]
    jb .done

    call scroll_screen
.done:
    ret

console_puts:
.next_char:
    lodsb
    test al, al
    jz .done

    cmp al, 10
    je .newline
    cmp al, 9
    je .tab
    cmp al, 8
    je .backspace

    call putc
    jmp .next_char

.newline:
    call console_newline
    jmp .next_char

.tab:
    mov ecx, 4
.tab_loop:
    mov al, ' '
    call putc
    loop .tab_loop
    jmp .next_char

.backspace:
    call backspace
    jmp .next_char

.done:
    ret

console_put_hex64:
    mov ecx, 16
    jmp put_hex_n

console_put_hex32:
    shl rax, 32
    mov ecx, 8
    jmp put_hex_n

console_put_dec64:
    push rax
    push rbx
    push rcx
    push rdx
    push rsi

    lea rsi, [rel dec_buffer_end]
    mov byte [rsi - 1], 0
    lea rsi, [rsi - 1]
    mov rbx, 10
    xor rcx, rcx

    test rax, rax
    jnz .convert
    mov al, '0'
    call putc
    jmp .done

.convert:
    xor rdx, rdx
    div rbx
    add dl, '0'
    dec rsi
    mov [rsi], dl
    inc rcx
    test rax, rax
    jnz .convert

.emit:
    mov al, [rsi]
    call putc
    inc rsi
    loop .emit

.done:
    pop rsi
    pop rdx
    pop rcx
    pop rbx
    pop rax
    ret

console_kprintf1:
    push rcx
    push rdx
    xor rcx, rcx
    jmp kprintf_common

console_kprintf2:
    push rcx
    push rdx
    jmp kprintf_common

console_panic:
    push rsi
    push rax
    mov eax, PANIC_BG_COLOR
    call fill_screen_color
    mov dword [cursor_x], 16
    mov dword [cursor_y], 16
    lea rsi, [rel panic_prefix]
    call console_puts
    pop rax
    pop rsi
    call console_puts
.hang:
    cli
    hlt
    jmp .hang

kprintf_common:
    push rax
    push rbx
    push rdi
    push r8
    push r9
    push r10
    push r11

    mov r8, rdx
    mov r9, rcx
    xor ebx, ebx

.next_char:
    lodsb
    test al, al
    jz .done
    cmp al, '%'
    jne .emit_char

    lodsb
    test al, al
    jz .done
    cmp al, '%'
    je .emit_char
    cmp al, 's'
    je .fmt_s
    cmp al, 'x'
    je .fmt_x
    cmp al, 'u'
    je .fmt_u
    cmp al, 'c'
    je .fmt_c
    jmp .emit_char

.emit_char:
    cmp al, 10
    je .emit_newline
    call putc
    jmp .next_char

.emit_newline:
    call console_newline
    jmp .next_char

.get_arg:
    cmp ebx, 0
    je .arg0
    mov rax, r9
    inc ebx
    ret
.arg0:
    mov rax, r8
    inc ebx
    ret

.fmt_s:
    call .get_arg
    push rsi
    mov rsi, rax
    call console_puts
    pop rsi
    jmp .next_char

.fmt_x:
    call .get_arg
    call console_put_hex64
    jmp .next_char

.fmt_u:
    call .get_arg
    call console_put_dec64
    jmp .next_char

.fmt_c:
    call .get_arg
    call putc
    jmp .next_char

.done:
    pop r11
    pop r10
    pop r9
    pop r8
    pop rdi
    pop rbx
    pop rax
    pop rdx
    pop rcx
    ret

put_hex_n:
    push rax
    push rbx
    push rcx
    push rdx

    mov rbx, rax

.hex_loop:
    mov rax, rbx
    shr rax, 60
    and al, 0x0F
    cmp al, 9
    jbe .digit
    add al, 'A' - 10
    jmp .emit
.digit:
    add al, '0'
.emit:
    call putc_simple
    shl rbx, 4
    loop .hex_loop

    pop rdx
    pop rcx
    pop rbx
    pop rax
    ret

backspace:
    push rax
    push rcx
    push rdx

    cmp dword [cursor_x], 16
    jbe .done
    sub dword [cursor_x], FONT_W

    mov eax, [cursor_x]
    mov ecx, [cursor_y]
    mov edx, BG_COLOR
    mov r8d, FONT_H
.row_loop:
    mov r9d, FONT_W
.col_loop:
    push rcx
    call put_pixel
    pop rcx
    inc eax
    dec r9d
    jnz .col_loop
    mov eax, [cursor_x]
    inc ecx
    dec r8d
    jnz .row_loop

.done:
    pop rdx
    pop rcx
    pop rax
    ret

putc:
    push rax
    call putc_simple
    pop rax
    ret

putc_simple:
    push rax
    push rbx
    push rcx
    push rdx
    push rsi
    push rdi
    push r8
    push r9
    push r10
    push r11

    mov bl, al
    mov eax, [cursor_x]
    add eax, FONT_W
    cmp eax, [fb_width]
    jbe .space_ok
    call console_newline

.space_ok:
    movzx eax, bl
    sub eax, 32
    cmp eax, 95
    jae .restore

    mov ebx, [cursor_x]
    mov ecx, [cursor_y]
    mov rsi, font_data
    mov edx, eax
    imul edx, FONT_H
    add rsi, rdx

    xor r8d, r8d
.row_loop:
    cmp r8d, FONT_H
    jae .advance

    movzx r9d, byte [rsi + r8]
    xor r10d, r10d
.col_loop:
    cmp r10d, FONT_W
    jae .next_row

    mov eax, r9d
    mov ecx, 7
    sub ecx, r10d
    shr eax, cl
    and eax, 1

    mov edx, BG_COLOR
    test eax, eax
    jz .draw
    mov edx, FG_COLOR

.draw:
    mov eax, ebx
    add eax, r10d
    mov ecx, [cursor_y]
    add ecx, r8d
    call put_pixel

    inc r10d
    jmp .col_loop

.next_row:
    inc r8d
    jmp .row_loop

.advance:
    add dword [cursor_x], FONT_W

.restore:
    pop r11
    pop r10
    pop r9
    pop r8
    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx
    pop rax
    ret

put_pixel:
    push rbx
    push rdi

    cmp eax, [fb_width]
    jae .out
    cmp ecx, [fb_height]
    jae .out

    mov edi, [fb_pitch]
    imul ecx, edi
    add ecx, eax
    shl rcx, 2

    mov rbx, [fb_base]
    add rbx, rcx
    mov dword [rbx], edx

.out:
    pop rdi
    pop rbx
    ret

fill_screen_color:
    push rcx
    push rdi
    push r8

    mov r8d, eax
    mov rdi, [fb_base]
    mov ecx, [fb_pitch]
    imul ecx, [fb_height]

.fill_loop:
    test ecx, ecx
    jz .done
    mov dword [rdi], r8d
    add rdi, 4
    dec ecx
    jmp .fill_loop

.done:
    pop r8
    pop rdi
    pop rcx
    ret

scroll_screen:
    push rax
    push rbx
    push rcx
    push rdx
    push rsi
    push rdi

    mov eax, FONT_H + 2
    mov ebx, [fb_pitch]
    imul eax, ebx
    shl rax, 2
    mov rdx, rax

    mov rsi, [fb_base]
    add rsi, rdx
    mov rdi, [fb_base]

    mov eax, [fb_height]
    sub eax, FONT_H + 2
    imul eax, ebx
    mov ecx, eax

.copy_loop:
    test ecx, ecx
    jz .clear_tail
    mov eax, [rsi]
    mov [rdi], eax
    add rsi, 4
    add rdi, 4
    dec ecx
    jmp .copy_loop

.clear_tail:
    mov eax, BG_COLOR
    mov ecx, FONT_H + 2
    imul ecx, ebx

.clear_loop:
    test ecx, ecx
    jz .done
    mov [rdi], eax
    add rdi, 4
    dec ecx
    jmp .clear_loop

.done:
    mov eax, [fb_height]
    sub eax, FONT_H + 2 + 16
    mov [cursor_y], eax
    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx
    pop rax
    ret

console_read_line:
    push rax
    push rbx
    push rcx
    push rdx
    push rsi
    push rdi
    push r8

    mov rbx, rdi
    mov r8d, ecx
    xor edx, edx

    mov byte [cursor_visible], 0
    mov dword [cursor_ticks], 0
    call cursor_draw
    mov byte [cursor_visible], 1

    test r8d, r8d
    jz .done
    dec r8d



.read_key:
    call read_key_ascii
    test al, al
    jnz .got_key

    inc dword [cursor_ticks]
    cmp dword [cursor_ticks], 500000
    jb .read_key

    mov dword [cursor_ticks], 0
    call cursor_toggle
    jmp .read_key

.got_key:
    cmp byte [cursor_visible], 0
    je .cursor_hidden
    call cursor_erase
    mov byte [cursor_visible], 0

.cursor_hidden:
    cmp al, 10
    je .enter
    cmp al, 8
    je .backspace

    cmp edx, r8d
    jae .draw_cursor

    mov [rbx + rdx], al
    inc edx
    call putc

.draw_cursor:
    call cursor_draw
    mov byte [cursor_visible], 1
    jmp .read_key


.backspace:
    test edx, edx
    jz .read_key

    dec edx
    mov byte [rbx + rdx], 0
    call backspace
    call cursor_draw
    mov byte [cursor_visible], 1
    jmp .read_key

.enter:
    cmp byte [cursor_visible], 0
    je .finish_line
    call cursor_erase
    mov byte [cursor_visible], 0

.finish_line:
    mov byte [rbx + rdx], 0
    call console_newline

.done:
    pop r8
    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx
    pop rax
    ret

read_key_ascii:
    push rdx
    push rsi

    in al, 0x64
    test al, 1
    jz .no_char

    in al, 0x60
    test al, 0x80
    jnz .no_char

    cmp al, 0x1C
    je .enter
    cmp al, 0x0E
    je .backspace

    movzx edx, al
    cmp edx, keymap_end - keymap
    jae .no_char

    lea rsi, [rel keymap]
    mov al, [rsi + rdx]
    jmp .done

.enter:
    mov al, 10
    jmp .done

.backspace:
    mov al, 8
    jmp .done

.no_char:
    xor eax, eax

.done:
    pop rsi
    pop rdx
    ret

CURSOR_COLOR equ 0x00FFFFFF

cursor_draw:
    push rax
    push rbx
    push rcx
    push rdx
    push rsi
    push rdi
    push r8
    push r9
    push r10

    mov edx, CURSOR_COLOR
    call cursor_fill_cell

    pop r10
    pop r9
    pop r8
    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx
    pop rax
    ret

cursor_erase:
    push rax
    push rbx
    push rcx
    push rdx
    push rsi
    push rdi
    push r8
    push r9
    push r10

    mov edx, BG_COLOR
    call cursor_fill_cell

    pop r10
    pop r9
    pop r8
    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx
    pop rax
    ret

cursor_fill_cell:
    mov rdi, [fb_base]

    mov eax, [cursor_y]
    mov ebx, [fb_pitch]
    imul eax, ebx
    add eax, [cursor_x]
    shl rax, 2
    add rdi, rax

    mov r10d, [fb_pitch]
    shl r10, 2
    mov r8d, FONT_H

.row_loop:
    mov rsi, rdi
    mov r9d, FONT_W

.col_loop:
    mov dword [rsi], edx
    add rsi, 4
    dec r9d
    jnz .col_loop

    add rdi, r10
    dec r8d
    jnz .row_loop
    ret

cursor_toggle:
    cmp byte [cursor_visible], 0
    je .draw

    call cursor_erase
    mov byte [cursor_visible], 0
    ret

.draw:
    call cursor_draw
    mov byte [cursor_visible], 1
    ret

